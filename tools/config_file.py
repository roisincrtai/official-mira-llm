def defaults_for(stage, scheme=None):
    """The rows for one modular trainer YAML; never include another stage's settings."""
    if stage not in _STAGE_CONFIG_KEYS:
        raise ValueError(f"no modular config schema for stage {stage!r}")
    wanted = _BASE_CONFIG_KEYS | _STAGE_CONFIG_KEYS[stage]
    selected = []
    for title, body in defaults(scheme):
        kept = [row for row in body if row[0] in wanted]
        if kept:
            selected.append((title, kept))
    return selected


