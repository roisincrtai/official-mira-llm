# ONE ABLATION CASE'S SECTION NAME. It is a SHAPE and not a list because the yaml decides which
# cases exist; ablation.run.geometry_section writes the same spelling from the other side:
# ablation_K<K>[_positive]_dr<d_r>_dm<d_m>, or the former ablation_order<K>[_positive]_bottleneck<d_r>_memory<d_m>.
ABLATION_GEOMETRY_SECTION = re.compile(
    r"^ablation_(?:k\d+(?:_positive)?_dr\d+_dm\d+|order\d+(?:_positive)?_bottleneck\d+_memory\d+)$",
    re.IGNORECASE)


def argv_for(values, stage=None):
    """The command-line tokens a yaml's settings amount to, for one stage.

    The same flags config.sh assembled into $COMMON_FLAGS and $<STAGE>_FLAGS, in the same
    order, so a stage resolves to the same values it always did."""
    groups = STAGE_GROUPS.get(stage, STAGE_GROUPS[None])
    known = {key.lower() for key, _group, _kind, _target in SPEC}
    known.update({"benchmark_pairs", "baselines", "ablation_pairs",
                  "ablation_activations", "ablation_lattice_order",
                  "ablation_coefficient_bottleneck", "ablation_memory_dimension",
                  "ablation_state_budget", "ablation_groups", "ablation_initializer",
                  "ablation_validation_tokens", "ablation_context_seed", "tokenize_pairs",
                  "ablation_moe_total_experts", "ablation_moe_shared_experts",
                  "ablation_moe_active_experts", "ablation_moe_expert_width",
                  "ablation_modulus_map", "ablation_argument_map", "ablation_horizon"})
    retired = sorted(RETIRED_SETTINGS & set(values))
    if retired:
        _say(f"[config] {len(retired)} retired setting(s) ignored: {', '.join(retired)} -- they "
             f"configured architectures this project no longer builds")
    known.update(RETIRED_SETTINGS)
    renamed = sorted(set(RENAMED_SETTINGS) & set(values))
    if renamed:
        raise SystemExit(f"[config] setting {renamed[0]!r} is replaced by "
                         f"{RENAMED_SETTINGS[renamed[0]]!r}"
                         f"{RENAMED_SETTING_NOTES.get(renamed[0], '')}")
    moved = [key for key in SCHEME_SETTINGS if key in values]
    if moved:
        raise SystemExit(f"[config] setting {moved[0]!r} is part of the MIRA scheme (2026-10-06): "
                         f"set it under the scheme in config/default/config_mira.yaml")
    known.update(section.lower() for section in (
        "mira_a", "mira_matrix", "mha", "rwkv_v6", "rwkv_v7", "mamba_v1", "mamba_v2", "mamba_v3", "retnet",
        "hgrn_v2", "gated_deltanet", "gated_deltanet_v2", "hyena", "xlstm"))
    known.update(key for key in values if ABLATION_GEOMETRY_SECTION.match(str(key)))
    unknown = sorted(set(values) - known)
    if unknown:
        raise SystemExit(f"[config] unknown setting {unknown[0]!r}")
    selected = [row for row in SPEC if row[1] in groups and row[2] != "shell"]
    last = {row[0].lower(): index for index, row in enumerate(selected)}
    out = []
    for index, (key, group, kind, target) in enumerate(selected):
        if index != last[key.lower()]:
            continue
        val = values.get(key.lower(), "")
        if kind == "free":
            if val:
                out += shlex.split(val)
        elif not val:
            continue                       # blank sets nothing; the default below it stands
        elif kind == "opt":
            out += [target, val]
        elif kind == "set":
            out += ["--set", f"{target}={val}"]
        elif kind == "off":
            if val == "0":
                out.append(target)
        elif kind == "on":
            if val == "1":
                out.append(target)
    return out


def path_in(argv, stage=None):
    """The path --config names in `argv`, or the default. Read BEFORE argparse, because what it
    names decides what argparse is given.

    THE LAST OCCURRENCE, because that is the one argparse itself would keep. A stage script
    that forwards its own arguments can produce two, and the two answers must agree or the file
    read would not be the file reported."""
    argv = list(argv or [])
    found = default_config(stage)
    for i, a in enumerate(argv):
        if a == "--config" and i + 1 < len(argv):
            found = argv[i + 1]
        elif a.startswith("--config="):
            found = a[len("--config="):]
    return found


def _say(m):
    """One line, from rank 0 alone. Under torchrun there are N processes and N copies of a line
    about a file they all read is N-1 lines of noise. RANK is torchrun's own; unset off it."""
    if os.environ.get("RANK", "0") == "0":
        print(m, flush=True)


def _print_loaded(path, settings=None):
    """Print the SETTINGS a trainer read from its yaml -- the parsed key/value pairs, aligned.

    Comments, blank lines and headings are not settings and are not printed. torchrun ranks
    other than zero stay silent.
    """
    if os.environ.get("RANK", "0") != "0":
        return
    rel = _rel(path)
    values = read(path) if settings is None else settings
    print(f"[config] {len(values)} setting(s) from {rel}", flush=True)
    if not values:
        return
    width = max(len(key) for key in values)
    for key in sorted(values):
        print(f"[config]   {key:<{width}}  {values[key]}", flush=True)


def resolve(argv=None, stage=None):
    """(tokens, path) -- the yaml layer for this run, ready to sit in front of `argv`.

    A missing selected fallback is not an error for legacy, non-modular stages: they run on
    default_config.py's values. The modular trainers ship tracked fallbacks, so their ordinary
    no-user-file path is concrete and reproducible.

    A MISSING FILE THE PERSON NAMED IS AN ERROR. `--config config/pretrain/config_pretrain.yam` is a
    typo, and a typo that silently trains on the defaults for three days is worse in every way
    than one that stops in the first second."""
    argv = list(sys.argv[1:] if argv is None else argv)
    default = default_config(stage)
    path = path_in(argv, stage)
    # BY PATH AND NOT BY SPELLING: a stage script runs from the checkout and says
    # an explicit spelling of the stage default, which is the same file, and a
    # relative spelling of the default must not turn a missing file into a stopped run.
    named = os.path.abspath(path) != os.path.abspath(default)
    if not os.path.isfile(path):
        if named:
            raise SystemExit(f"[config] --config {path}: no such file. Write one with "
                             f"`python -m tools.config_wizard --out {path}`, or drop --config "
                             f"to use {_rel(default)}.")
        _say(f"config: {_rel(path)}")
        _say(f"[config] no {_rel(path)}; every setting from default_config.py")
        return [], path
    values = read(path)
    tokens = argv_for(values, stage)
    _say(f"config: {_rel(path)}")
    _print_loaded(path, values)
    return tokens, path


