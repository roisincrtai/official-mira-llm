    index = 0
    while index < len(lines):
        raw = lines[index]
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip() or ":" not in line:
            index += 1
            continue
        indent = len(line) - len(line.lstrip(" "))
        key, _, value = line.strip().partition(":")
        key = key.lower()
        if value.strip():
            index += 1
            continue
        child = index + 1
