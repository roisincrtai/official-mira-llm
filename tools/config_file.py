# line is taken as typed, because that is what a person at a prompt means by a relative path.
CONFIG_DIR = os.path.join(config.ROOT, "config")


MODULAR_STAGES = {
    "pretrain", "instruct_sft", "instruct_reward", "instruct_rlhf", "instruct_dpo",
}


def user_config(stage=None):
    """The optional, untracked user override for one trainer."""
    return os.path.join(CONFIG_DIR, stage or "pretrain", "config_user.yaml")


def fallback_config(stage=None):
    """The tracked fallback for one trainer when its user override does not exist."""
    stage = stage or "pretrain"
    if stage == "benchmark":
        return os.path.join(CONFIG_DIR, "benchmark", "config_benchmark.yaml")
    if stage == "pretrain":
        # ONE PRETRAIN YAML (2026-10-09), whatever the scheme; the instruct stages keep theirs.
        return os.path.join(CONFIG_DIR, "pretrain", "config_pretrain.yaml")
    if stage in MODULAR_STAGES:
        return os.path.join(CONFIG_DIR, stage, f"config_{config.DEFAULT_SCHEME}.yaml")
    # Stages outside the modular training set retain their default_config.py behavior when no
    # user file exists; resolve() already treats a missing default path as "use Python defaults".
    return user_config(stage)


def default_config(stage=None):
    """Selected YAML: an existing user override first, otherwise the tracked fallback."""
    user = user_config(stage)
    return user if os.path.isfile(user) else fallback_config(stage)


