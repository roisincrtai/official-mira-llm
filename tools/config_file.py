PRETRAIN_STEPS_TODAY = 250000


def _b(v):
    """A bool as the shell spells it, because that is what the value has always looked like."""
    return "1" if v else "0"


def _rel(path):
    """Relative to the checkout: an absolute path in a file read on a laptop and on a cluster
    is noise wherever it was not produced."""
    try:
        return os.path.relpath(path, config.ROOT)
    except ValueError:
        return path


