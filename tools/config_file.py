"""
tools/config_file.py -- THE YAML LAYER. One file of settings, read by the trainers themselves.

IT LIVES UNDER tools/ AND NOT UNDER helpers/ FOR ONE REASON: `import helpers` imports
helpers.utils, which imports torch. This module has to be importable where torch is not --
tools/config_wizard.py writes a configuration on a login node, and default_config.py is
deliberately importable without torch for exactly the same reason. model/lm.py already
uses this module through helpers/common.py, so keeping this layer torch-free also keeps the
configuration wizard usable on a login node.

    default_config.py   <   the yaml named by --config   <   the flags on the command line

WHAT IT REPLACED, AND WHY THE SHAPE IS WHAT IT IS. config.sh held every setting as a shell
variable, assembled COMMON_FLAGS and <STAGE>_FLAGS from them, and each stage<N>_*.sh ran

    python -m pretrain.run $COMMON_FLAGS $PRETRAIN_FLAGS "$@"

so the trainer received its configuration as an ordinary command line and knew nothing about
where it came from. Everything below is that assembly, moved from bash into python and driven
by a yaml file instead of by exported variables. The retired memory-limit solver is the one
intentional omission: batch, micro-batch and checkpointing are now ordinary explicit settings.

THE KEYS ARE STILL THE SHELL SPELLINGS -- GPU, PRETRAIN_STEPS, COT_GROUP. They are what
the former shell framework used and what existing generated files contain, so those files stay
readable while the trainers use only the YAML layer.

ARGPARSE DOES THE PRECEDENCE, AND NOTHING HERE HAS TO. The tokens this module produces are
placed BEFORE the user's own argv, and argparse keeps the last occurrence of a repeated
option -- so `--batch 8` typed at a prompt beats `BATCH: 56` in the file, with no per-setting
plumbing, exactly as `"$@"` after $COMMON_FLAGS did.

A MISSING USER FILE IS NOT AN ERROR: the trainer selects its tracked fallback instead. A file
the person NAMED with --config and which is not there IS an error:
a typo that silently trains on the defaults is a run nobody can explain afterwards.

THE FORMAT is the small flat-YAML subset generated by tools/config_wizard.py and parsed here:

    # comments, to end of line
    section:                 # a bare key with no value: a heading, ignored
      GPU: cuda              # KEY: value
      BATCH:                 # empty value: sets nothing, the default stands
      PRETRAIN_FLAGS: ""     # quotes are stripped; free text appended to the command line
"""
